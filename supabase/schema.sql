-- E-mails do pessoal da loja. Só quem está aqui (e logado) cadastra, edita e exclui.
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;
-- Sem políticas: ninguém lê nem altera esta tabela pelo site, só pelo painel do Supabase.

create or replace function public.eh_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- ---------------------------------------------------------------------------
-- Veículos
-- ---------------------------------------------------------------------------

create table if not exists public.veiculos (
  id          bigint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  marca       text not null check (length(trim(marca)) > 0),
  modelo      text not null check (length(trim(modelo)) > 0),
  versao      text not null default '',
  ano         int  not null check (ano between 1900 and 2100),
  km          int  check (km >= 0),
  preco       int  check (preco > 0),
  cambio      text check (cambio in ('Manual', 'Automático')),
  combustivel text check (combustivel in ('Flex', 'Gasolina')),
  carroceria  text not null check (carroceria in ('Hatch', 'Sedan', 'SUV', 'Minivan', 'Perua', 'Moto')),
  situacao    text not null default 'Disponível' check (situacao in ('Disponível', 'Reservado', 'Vendido')),
  importado   boolean not null default false,
  cor         text not null default '#3B6296',
  fotos       jsonb not null default '[]'::jsonb,
  itens       text[] not null default '{}',
  criado_em   timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

alter table public.veiculos enable row level security;

-- Visitantes veem o que está à venda; a loja vê tudo (inclusive vendidos)
drop policy if exists "ver veiculos" on public.veiculos;
create policy "ver veiculos" on public.veiculos
  for select to anon, authenticated
  using (situacao <> 'Vendido' or public.eh_admin());

drop policy if exists "loja cadastra" on public.veiculos;
create policy "loja cadastra" on public.veiculos
  for insert to authenticated
  with check (public.eh_admin());

drop policy if exists "loja edita" on public.veiculos;
create policy "loja edita" on public.veiculos
  for update to authenticated
  using (public.eh_admin())
  with check (public.eh_admin());

drop policy if exists "loja exclui" on public.veiculos;
create policy "loja exclui" on public.veiculos
  for delete to authenticated
  using (public.eh_admin());

create or replace function public.tocar_atualizado_em()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists veiculos_atualizado_em on public.veiculos;
create trigger veiculos_atualizado_em
  before update on public.veiculos
  for each row execute function public.tocar_atualizado_em();

-- ---------------------------------------------------------------------------
-- Fotos (Storage)
-- ---------------------------------------------------------------------------

-- Bucket público para leitura; até 5 MB por arquivo, só imagens
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('veiculos', 'veiculos', true, 5242880, array['image/webp', 'image/jpeg', 'image/png'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "loja envia fotos" on storage.objects;
create policy "loja envia fotos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'veiculos' and public.eh_admin());

drop policy if exists "loja troca fotos" on storage.objects;
create policy "loja troca fotos" on storage.objects
  for update to authenticated
  using (bucket_id = 'veiculos' and public.eh_admin());

drop policy if exists "loja apaga fotos" on storage.objects;
create policy "loja apaga fotos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'veiculos' and public.eh_admin());

